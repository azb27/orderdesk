"""Write docs/results/failures.md: real examples of each kind of error, from a stored run (no API calls).

    python -m evals.failures [--config sonnet] [--split test] [--per-kind 5]

Examples are spread evenly over the sorted conversation ids, so the file is the same on every run.
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict

from evals.report import LABELS, STYLE, W, classify, load_runs, load_truth
from orderdesk import config

OUT = config.ROOT / "docs" / "results" / "failures.md"


def conversations(split: str) -> dict[str, dict]:
    path = config.EVAL / split / "conversations.jsonl"
    return {c["id"]: c for c in map(json.loads, path.read_text().splitlines())}


def name(sku: str | None) -> str:
    return "–" if sku is None else W.skus[sku]["name_en"]


def describe_truth(t: dict, sku: str) -> str:
    ln = next(x for x in t["lines"] if x["sku"] == sku)
    how = {
        "term": f"written as “{ln.get('term', '')}”",
        "nickname": "the customer's nickname",
        "history": "from their last order",
    }
    bits = [how.get(ln["via"], ln["via"]), STYLE.get(ln.get("style", ""), "")]
    if ln["via"] == "term":
        bits.append("held-out name" if not ln.get("term_seen") else "")
        bits.append("size not written" if not ln.get("size_given") else "")
        bits.append("unit not written" if not ln.get("unit_given") else "")
    return f"{name(sku)}, {ln['qty']} {ln['unit']} ({', '.join(b for b in bits if b)})"


def describe_pred(row: dict, sku: str | None) -> str:
    if sku is None:
        return "nothing"
    ln = next(x for x in row["lines"] if x.get("sku") == sku)
    why = f" — model: “{ln['why']}”" if ln.get("why") else ""
    src = f" from “{ln['source']}”" if ln.get("source") else ""
    return f"{name(sku)}, {ln['qty']} {ln['unit']}{src}{why}"


def message_text(c: dict) -> str:
    parts = []
    for m in c["messages"]:
        if m["type"] == "image":
            parts.append(f"[photo of a handwritten list: `data/eval/{m.get('image', '')}`]")
        else:
            parts.append(m.get("text") or "")
    return " ⏎ ".join(p.replace("\n", " ⏎ ") for p in parts)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="sonnet")
    ap.add_argument("--split", default="test")
    ap.add_argument("--per-kind", type=int, default=5)
    a = ap.parse_args()
    truth = load_truth(a.split)
    rows = load_runs(a.split, truth)[a.config]
    convs = conversations(a.split)
    errors: dict[str, list[tuple[str, str | None, str | None]]] = defaultdict(list)
    for cid in sorted(truth):
        if cid in rows:
            for kind, t, p in classify(truth[cid]["lines"], rows[cid]["lines"]):
                errors[kind].append((cid, t, p))
    L = [f"# Orderdesk eval: examples of each error ({LABELS[a.config]}, {a.split} split)", "",
         f"Generated by `python -m evals.failures --config {a.config} --split {a.split}` from the stored run. Do not edit by hand. "
         "Examples are spread evenly over the conversation ids, not picked. Counts match the taxonomy in `eval.md`.", ""]  # fmt: skip
    for kind, errs in sorted(errors.items(), key=lambda kv: -len(kv[1])):
        L += [f"## {kind} ({len(errs)})", ""]
        step = max(1, len(errs) // a.per_kind)
        for cid, t, p in errs[::step][: a.per_kind]:
            c, r = convs[cid], rows[cid]
            L.append(f"**{cid}** ({c['channel']}, {truth[cid]['kind']})")
            L.append(f"> {message_text(c)[:400]}")
            L.append("")
            if t:
                L.append(f"- Ordered: {describe_truth(truth[cid], t)}")
            L.append(f"- Drafted: {describe_pred(r, p)}")
            L.append("")
    OUT.write_text("\n".join(L) + "\n")
    print(f"wrote {OUT}: " + ", ".join(f"{k} {len(v)}" for k, v in errors.items()))


if __name__ == "__main__":
    main()
